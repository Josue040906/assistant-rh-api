-- La table reclassement existait avant V20261027_01 sous une forme réduite
-- (employe_id, id_activite, categorie_id) : CREATE TABLE IF NOT EXISTS ne l'a
-- pas remplacée, et l'enregistrement d'un reclassement échouait. On la remet
-- à la structure attendue, en reconstituant chaque ligne déjà présente à partir
-- de son activité (diplôme retenu) et de l'historique de carrière (avant/après).

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'reclassement')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_name = 'reclassement' AND column_name = 'categorie_avant_id') THEN
        EXECUTE 'ALTER TABLE reclassement RENAME TO reclassement_ancien';
        EXECUTE 'ALTER TABLE reclassement_ancien RENAME CONSTRAINT reclassement_pkey TO reclassement_ancien_pkey';
        EXECUTE 'ALTER TABLE reclassement_ancien RENAME CONSTRAINT reclassement_id_activite_key TO reclassement_ancien_id_activite_key';
        EXECUTE 'ALTER INDEX IF EXISTS idx_reclassement_employe RENAME TO idx_reclassement_ancien_employe';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS reclassement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employe_id INTEGER NOT NULL,
    id_activite INTEGER NOT NULL UNIQUE,
    employe_diplome_id INTEGER NOT NULL,
    historique_avant_id INTEGER,
    historique_apres_id INTEGER,
    categorie_avant_id INTEGER NOT NULL,
    categorie_apres_id INTEGER NOT NULL,
    corps_avant_id INTEGER,
    corps_apres_id INTEGER,
    date_effet DATE NOT NULL,
    date_creation TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reclassement_employe FOREIGN KEY (employe_id) REFERENCES employe(id),
    CONSTRAINT fk_reclassement_activite FOREIGN KEY (id_activite) REFERENCES activite(id),
    CONSTRAINT fk_reclassement_employe_diplome FOREIGN KEY (employe_diplome_id) REFERENCES employe_diplome(id),
    CONSTRAINT fk_reclassement_historique_avant FOREIGN KEY (historique_avant_id) REFERENCES historique_carriere(id),
    CONSTRAINT fk_reclassement_historique_apres FOREIGN KEY (historique_apres_id) REFERENCES historique_carriere(id),
    CONSTRAINT fk_reclassement_categorie_avant FOREIGN KEY (categorie_avant_id) REFERENCES categorie(id),
    CONSTRAINT fk_reclassement_categorie_apres FOREIGN KEY (categorie_apres_id) REFERENCES categorie(id),
    CONSTRAINT fk_reclassement_corps_avant FOREIGN KEY (corps_avant_id) REFERENCES corps(id),
    CONSTRAINT fk_reclassement_corps_apres FOREIGN KEY (corps_apres_id) REFERENCES corps(id),
    CONSTRAINT ck_reclassement_changement_classification CHECK (
        categorie_avant_id <> categorie_apres_id
        OR corps_avant_id IS DISTINCT FROM corps_apres_id
    )
);

CREATE INDEX IF NOT EXISTS idx_reclassement_employe_date
    ON reclassement (employe_id, date_effet DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_reclassement_diplome
    ON reclassement (employe_diplome_id);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'reclassement_ancien') THEN
        EXECUTE $sql$
            INSERT INTO reclassement (
                id, employe_id, id_activite, employe_diplome_id,
                historique_avant_id, historique_apres_id,
                categorie_avant_id, categorie_apres_id, corps_avant_id, corps_apres_id,
                date_effet, date_creation
            )
            SELECT ancien.id, ancien.employe_id, ancien.id_activite,
                   SUBSTRING(a.description FROM 'diplôme agent #([0-9]+)')::int,
                   avant.id, apres.id,
                   avant.categorie_id, ancien.categorie_id, cav.corps_id, cap.corps_id,
                   apres.date_debut, a.date_heure
            FROM reclassement_ancien ancien
            JOIN activite a ON a.id = ancien.id_activite
            JOIN historique_carriere apres
              ON apres.employe_id = ancien.employe_id AND apres.date_debut = a.date_heure::date
            JOIN historique_carriere avant
              ON avant.employe_id = ancien.employe_id AND avant.date_fin = apres.date_debut - 1
            JOIN categorie cav ON cav.id = avant.categorie_id
            JOIN categorie cap ON cap.id = ancien.categorie_id
        $sql$;
        -- Toute ligne ancienne doit avoir été reconstituée, sinon rien n'est changé.
        IF (SELECT COUNT(*) FROM reclassement_ancien) <> (SELECT COUNT(*) FROM reclassement) THEN
            RAISE EXCEPTION 'Reclassements anciens non reconstitués : migration annulée.';
        END IF;
        EXECUTE 'DROP TABLE reclassement_ancien';
        PERFORM setval(pg_get_serial_sequence('reclassement', 'id'),
                       GREATEST((SELECT MAX(id) FROM reclassement), 1));
    END IF;
END $$;
