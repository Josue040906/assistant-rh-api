-- Historique métier structuré des reclassements.
-- L'activité associée conserve l'auteur, l'horodatage et le journal générique.
-- Cette table conserve les situations et classifications avant/après sans parser la description d'activité.

CREATE TABLE IF NOT EXISTS reclassement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employe_id INTEGER NOT NULL,
    id_activite INTEGER NOT NULL UNIQUE,
    employe_diplome_id INTEGER NOT NULL,

    historique_avant_id INTEGER,
    historique_apres_id INTEGER,

    categorie_avant_id INTEGER NOT NULL,
    categorie_apres_id INTEGER NOT NULL,
    corps_avant_id INTEGER,
    corps_apres_id INTEGER,

    date_effet DATE NOT NULL,
    date_creation TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reclassement_employe
        FOREIGN KEY (employe_id) REFERENCES employe(id),
    CONSTRAINT fk_reclassement_activite
        FOREIGN KEY (id_activite) REFERENCES activite(id),
    CONSTRAINT fk_reclassement_employe_diplome
        FOREIGN KEY (employe_diplome_id) REFERENCES employe_diplome(id),
    CONSTRAINT fk_reclassement_historique_avant
        FOREIGN KEY (historique_avant_id) REFERENCES historique_carriere(id),
    CONSTRAINT fk_reclassement_historique_apres
        FOREIGN KEY (historique_apres_id) REFERENCES historique_carriere(id),
    CONSTRAINT fk_reclassement_categorie_avant
        FOREIGN KEY (categorie_avant_id) REFERENCES categorie(id),
    CONSTRAINT fk_reclassement_categorie_apres
        FOREIGN KEY (categorie_apres_id) REFERENCES categorie(id),
    CONSTRAINT fk_reclassement_corps_avant
        FOREIGN KEY (corps_avant_id) REFERENCES corps(id),
    CONSTRAINT fk_reclassement_corps_apres
        FOREIGN KEY (corps_apres_id) REFERENCES corps(id),

    CONSTRAINT ck_reclassement_changement_classification
        CHECK (
            categorie_avant_id <> categorie_apres_id
            OR corps_avant_id IS DISTINCT FROM corps_apres_id
        )
);

CREATE INDEX IF NOT EXISTS idx_reclassement_employe_date
    ON reclassement (employe_id, date_effet DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_reclassement_diplome
    ON reclassement (employe_diplome_id);

COMMENT ON TABLE reclassement IS
    'Historique métier des reclassements effectivement appliqués; id_activite référence leur entrée dans le journal d''activité.';
COMMENT ON COLUMN reclassement.id_activite IS
    'Activité générique liée au reclassement; permet de retrouver l''acteur et l''horodatage dans activite.';
COMMENT ON COLUMN reclassement.employe_diplome_id IS
    'Diplôme de l''agent retenu comme justification du reclassement.';
