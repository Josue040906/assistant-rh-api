CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS localite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    niveau VARCHAR(16) NOT NULL
        CHECK (niveau IN ('REGION', 'DISTRICT', 'COMMUNE', 'FOKONTANY')),
    nom VARCHAR(200) NOT NULL CHECK (btrim(nom) <> ''),
    parent_id BIGINT,
    parent_niveau VARCHAR(16),
    origine VARCHAR(16) NOT NULL DEFAULT 'HDX_OCHA'
        CHECK (origine IN ('HDX_OCHA', 'MANUEL')),
    source_name VARCHAR(100),
    source_code VARCHAR(64),
    source_version VARCHAR(32),
    source_valid_on DATE,
    source_valid_to DATE,
    source_license VARCHAR(100),
    imported_at TIMESTAMPTZ,
    CONSTRAINT uq_localite_id_niveau UNIQUE (id, niveau),
    CONSTRAINT fk_localite_parent_niveau
        FOREIGN KEY (parent_id, parent_niveau)
        REFERENCES localite (id, niveau),
    CONSTRAINT ck_localite_parent_level CHECK (
        (niveau = 'REGION' AND parent_id IS NULL AND parent_niveau IS NULL)
        OR (niveau = 'DISTRICT' AND parent_id IS NOT NULL AND parent_niveau = 'REGION')
        OR (niveau = 'COMMUNE' AND parent_id IS NOT NULL AND parent_niveau = 'DISTRICT')
        OR (niveau = 'FOKONTANY' AND parent_id IS NOT NULL AND parent_niveau = 'COMMUNE')
    ),
    CONSTRAINT ck_localite_source_code CHECK (
        (origine = 'HDX_OCHA' AND source_name IS NOT NULL AND source_code IS NOT NULL)
        OR (origine = 'MANUEL' AND source_code IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_localite_source_code
    ON localite (source_name, source_code)
    WHERE source_code IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_localite_parent_niveau
    ON localite (parent_id, niveau, id);

CREATE INDEX IF NOT EXISTS ix_localite_nom_trgm
    ON localite USING GIN (lower(nom) gin_trgm_ops);

ALTER TABLE employe
    ADD COLUMN IF NOT EXISTS localite_residence_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_employe_localite_residence'
          AND conrelid = 'employe'::regclass
    ) THEN
        ALTER TABLE employe
            ADD CONSTRAINT fk_employe_localite_residence
            FOREIGN KEY (localite_residence_id) REFERENCES localite (id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS ix_employe_localite_residence
    ON employe (localite_residence_id)
    WHERE localite_residence_id IS NOT NULL;
