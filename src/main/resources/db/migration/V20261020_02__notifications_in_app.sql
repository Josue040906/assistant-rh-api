CREATE TABLE IF NOT EXISTS notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire_id INTEGER NOT NULL
        REFERENCES utilisateur(id) ON DELETE CASCADE,
    type VARCHAR(40) NOT NULL
        CHECK (type IN (
            'NOUVEL_AGENT',
            'ANCIENNETE_UN_MOIS',
            'ANCIENNETE_ATTEINTE'
        )),
    titre VARCHAR(160) NOT NULL,
    message TEXT NOT NULL,
    employe_id INTEGER REFERENCES employe(id) ON DELETE SET NULL,
    acteur_id INTEGER REFERENCES utilisateur(id) ON DELETE SET NULL,
    cle_deduplication VARCHAR(160) NOT NULL,
    cree_le TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lu_le TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_notification_destinataire_cle
        UNIQUE (destinataire_id, cle_deduplication)
);

CREATE INDEX IF NOT EXISTS idx_notification_destinataire_date
    ON notification (destinataire_id, cree_le DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_notification_non_lue
    ON notification (destinataire_id, id)
    WHERE lu_le IS NULL;
